/**
 * Translate a translation key to the requested language
 */
export function t(key: string, lang: LanguageCode = 'en'): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS['en'];
  if (dict && dict[key]) {
    return dict[key];
  }
  // Fallback to English
  if (TRANSLATIONS['en'][key]) {
    return TRANSLATIONS['en'][key];
  }
  return key;
}

/**
 * Helper to get font class based on language
 */
export function getLanguageFontClass(lang: LanguageCode): string {
  if (lang === 'ur') return 'font-urdu';
  if (lang === 'hi') return 'font-devanagari';
  return 'font-outfit';
}
